import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import { BridgeRunner } from '../src/host/bridge-runner.ts';
import { OperationLedger } from '../src/host/operation-ledger.ts';
import { WorkService } from '../src/host/work-service.ts';
import { DraftService } from '../src/host/draft-service.ts';
import { DraftStore } from '../src/host/draft-store.ts';
import type { TaskDTO, TaskLogDTO } from '../src/shared/contracts.ts';

test('fixed subprocess interoperates with Python protocol: all six operations, CAS, replay and shared draft', async () => {
  const root = await mkdtemp(join(tmpdir(), 'dsh-work-real-bridge-'));
  const runner = new BridgeRunner({ projectRoot: resolve('../..'), dataDir: join(root, 'core space;$(not-a-command)') });
  const work = new WorkService(runner, new OperationLedger(join(root, 'receipts')));
  const drafts = new DraftService(work, new DraftStore(join(root, 'drafts')));
  const created = await work.submit('integration', { kind: 'create', title: '真实桥接中文测试', content: '未经过模型', tags: ['测试'] }, 'create-command');
  assert.equal(created.state, 'SUCCEEDED', JSON.stringify(created)); assert.match(created.task_id!, /^task_[a-f0-9]{32}$/);
  assert.equal(created.result?.revision, 1);
  const follow = await work.submit('integration', { kind: 'follow', task_id: created.task_id!, content: '第一次跟进' }, 'follow-command');
  assert.equal(follow.state, 'SUCCEEDED', JSON.stringify(follow)); assert.equal(follow.expected_revision, 1); assert.ok(follow.result?.log_id);
  const done = await work.submit('integration', { kind: 'set_status', task_id: created.task_id!, expected_revision: 2, status: 'completed' }, 'done-command');
  assert.equal(done.state, 'SUCCEEDED', JSON.stringify(done)); assert.equal(done.result?.revision, 3);
  const detail = await work.query('integration', { kind: 'get', task_id: created.task_id! });
  assert.equal((detail.data as TaskDTO).status, 'completed'); assert.deepEqual(detail.binding, created.binding);
  const logs = await work.query('integration', { kind: 'logs', task_id: created.task_id!, after: 0, limit: 200 });
  assert.equal((logs.data as TaskLogDTO[]).length, 1); assert.equal((logs.data as TaskLogDTO[])[0].task_revision, 2);
  const list = await work.query('integration', { kind: 'list', status: 'completed' }); assert.equal((list.data as TaskDTO[]).length, 1);
  const conflict = await work.submit('integration', { kind: 'edit', task_id: created.task_id!, expected_revision: 1, changes: { title: 'stale' } }, 'stale');
  assert.equal(conflict.state, 'REJECTED'); assert.equal(conflict.error?.code, 'conflict'); assert.equal(conflict.error?.details?.actual_revision, 3);
  const replay = await work.submit('integration', { kind: 'create', title: 'different', content: 'different' }, 'create-command'); assert.equal(replay.operation_id, created.operation_id);
  const shared = await drafts.saveDraft('integration', { kind: 'create', expected_draft_revision: 0, mutation_id: 'draft-save', payload: { title: '另一设备稿', content: '共享稿', tags: ['共享'], tags_text: '共享', arbitrary_ui_state: true } });
  const [a,b] = await Promise.all([drafts.submitDraft('integration', shared.draft_id, 1), drafts.submitDraft('integration', shared.draft_id, 1)]);
  assert.equal(a.state, 'SUCCEEDED', JSON.stringify(a)); assert.equal(a.operation_id, b.operation_id);
  assert.equal(((await work.query('integration', { kind: 'list' })).data as TaskDTO[]).length, 2);
  const controller = new AbortController();
  const aborted = work.runner.run({ protocol_version: '1', call_id: 'abort-live-child', operation: 'task.list', params: { limit: 1 } }, controller.signal);
  controller.abort();
  await assert.rejects(aborted, /cancelled/);
});
